# accept 2 numbers from the users and add,subtract,multiply and divide those numbers and print the results
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))
addition = num1 + num2
substraction = num1-num2
multiplication = num1 * num2
division = num1/num2
print(f" The sum of {num1} and {num2} is: {addition}\n The difference of {num1} and {num2} is: {substraction}\n The product of {num1} and {num2} is: {multiplication}\n The quotient of {num1} and {num2} is: {division}")